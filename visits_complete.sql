-- =========================================================
-- 11) إحصائيات شركة عامة/لصاحب الصلاحية
--
-- لا نفترض وجود company_id داخل profiles لأن schema الحالي
-- الذي راجعناه لا يحتوي على هذا الربط.
-- لذلك هذه الدالة للمدير فقط.
-- =========================================================

drop function if exists public.admin_company_visitor_stats(uuid);

