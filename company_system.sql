-- شركة كيان مستقل: المستخدمون المرتبطون بالشركة والصلاحيات
create table if not exists public.company_users (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null unique references auth.users(id) on delete cascade,
  company_id uuid not null references public.companies(id) on delete cascade,
  can_manage_products boolean not null default false,
  can_edit_products boolean not null default false,
  can_delete_products boolean not null default false,
  can_manage_categories boolean not null default false,
  can_manage_settings boolean not null default false,
  can_view_orders boolean not null default false,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists company_users_company_idx on public.company_users(company_id);
create index if not exists company_users_active_idx on public.company_users(active);

create table if not exists public.company_account_requests (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null unique references auth.users(id) on delete cascade,
  requested_name text,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  company_id uuid references public.companies(id) on delete set null,
  rejection_reason text,
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by uuid references auth.users(id) on delete set null
);
create index if not exists company_account_requests_status_idx on public.company_account_requests(status);

-- تصنيفات منتجات الشركات
create table if not exists public.company_categories (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  name text not null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(company_id,name)
);
create index if not exists company_categories_company_idx on public.company_categories(company_id);

-- منتجات مستقلة للشركة. السعر اختياري بالكامل.
create table if not exists public.company_products (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  name text not null,
  brand text,
  unit text,
  category text,
  category_id uuid references public.company_categories(id) on delete set null,
  barcode text,
  description text,
  image_url text,
  price_new numeric(14,2),
  active boolean not null default true,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists company_products_company_idx on public.company_products(company_id);
create index if not exists company_products_barcode_idx on public.company_products(barcode);
create index if not exists company_products_category_idx on public.company_products(category);
create unique index if not exists company_products_company_barcode_uq
  on public.company_products(company_id, barcode)
  where barcode is not null and length(trim(barcode)) > 0;

-- زيارات صفحات الشركات
create table if not exists public.company_visitor_visits (
  id bigint generated by default as identity primary key,
  company_id uuid not null references public.companies(id) on delete cascade,
  visitor_id text,
  created_at timestamptz not null default now()
);
create index if not exists company_visits_company_idx on public.company_visitor_visits(company_id);
create index if not exists company_visits_created_idx on public.company_visitor_visits(created_at);

