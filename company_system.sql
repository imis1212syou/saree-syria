-- حماية الحقول الحساسة للملف الشخصي من التعديل الذاتي
create or replace function public.protect_profile_privilege_fields()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
begin
  if auth.uid() is not null and auth.uid() <> old.id and not public.is_admin() then
    raise exception 'غير مسموح بتعديل حساب مستخدم آخر';
  end if;
  if auth.uid() = old.id and not public.is_admin() then
    if new.role is distinct from old.role
       or new.store_id is distinct from old.store_id
       or new.company_id is distinct from old.company_id
       or new.can_edit_prices is distinct from old.can_edit_prices
       or new.verified is distinct from old.verified then
      raise exception 'لا يمكن للحساب تعديل الدور أو الربط أو الصلاحيات بنفسه';
    end if;
  end if;
  return new;
end $$;

drop trigger if exists protect_profile_privilege_fields on public.profiles;
create trigger protect_profile_privilege_fields
before update on public.profiles
for each row execute function public.protect_profile_privilege_fields();

