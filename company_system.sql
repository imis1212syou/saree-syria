create or replace function public.company_can(p_company_id uuid, p_permission text)
returns boolean
language sql
security definer
set search_path=public
stable
as $$
  select exists(
    select 1 from public.company_users cu
    where cu.user_id=auth.uid()
      and cu.company_id=p_company_id
      and cu.active=true
      and (
        (p_permission='manage_products' and cu.can_manage_products)
        or (p_permission='edit_products' and cu.can_edit_products)
        or (p_permission='delete_products' and cu.can_delete_products)
        or (p_permission='manage_categories' and cu.can_manage_categories)
        or (p_permission='manage_settings' and cu.can_manage_settings)
        or (p_permission='view_orders' and cu.can_view_orders)
      )
  );
$$;

