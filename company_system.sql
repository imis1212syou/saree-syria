-- طلب ربط حساب شركة
create or replace function public.request_company_account(p_requested_name text default null)
returns uuid
language plpgsql
security definer
set search_path=public
as $$
declare v_id uuid;
begin
  if auth.uid() is null then raise exception 'يجب تسجيل الدخول'; end if;
  insert into public.company_account_requests(user_id,requested_name,status)
  values(auth.uid(), nullif(trim(coalesce(p_requested_name,'')),''), 'pending')
  on conflict (user_id) do update set
    requested_name=coalesce(excluded.requested_name, public.company_account_requests.requested_name),
    status=case when public.company_account_requests.status='rejected' then 'pending' else public.company_account_requests.status end,
    rejection_reason=null;
  select id into v_id from public.company_account_requests where user_id=auth.uid();
  return v_id;
end $$;
revoke all on function public.request_company_account(text) from public;
grant execute on function public.request_company_account(text) to authenticated;

