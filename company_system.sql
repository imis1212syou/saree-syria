-- وظائف إدخال المنتجات من حساب الشركة
create or replace function public.company_add_product(
  p_name text,
  p_brand text default null,
  p_unit text default null,
  p_category text default null,
  p_category_id uuid default null,
  p_barcode text default null,
  p_description text default null,
  p_image_url text default null,
  p_price_new numeric default null
)
returns uuid
language plpgsql
security definer
set search_path=public
as $$
declare v_company uuid; v_id uuid;
begin
  select company_id into v_company from public.company_users where user_id=auth.uid() and active=true;
  if v_company is null then raise exception 'حساب الشركة غير مرتبط'; end if;
  if not public.company_can(v_company,'manage_products') then raise exception 'لا توجد صلاحية إضافة المنتجات'; end if;
  if trim(coalesce(p_name,''))='' then raise exception 'اسم المادة مطلوب'; end if;
  if p_barcode is not null and trim(p_barcode)='' then p_barcode=null; end if;
  if p_price_new is not null and p_price_new < 0 then raise exception 'السعر غير صالح'; end if;
  insert into public.company_products(company_id,name,brand,unit,category,category_id,barcode,description,image_url,price_new,active,created_by)
  values(v_company,trim(p_name),nullif(trim(p_brand),''),nullif(trim(p_unit),''),nullif(trim(p_category),''),p_category_id,nullif(trim(p_barcode),''),p_description,p_image_url,p_price_new,true,auth.uid())
  returning id into v_id;
  return v_id;
end $$;
revoke all on function public.company_add_product(text,text,text,text,uuid,text,text,text,numeric) from public;
grant execute on function public.company_add_product(text,text,text,text,uuid,text,text,text,numeric) to authenticated;

