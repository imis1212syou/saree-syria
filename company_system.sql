-- المدير: ربط حساب الشركة بالشركة وتحديد كامل الصلاحيات
create or replace function public.admin_link_company_account(
  p_request_id uuid,
  p_company_id uuid,
  p_can_manage_products boolean default false,
  p_can_edit_products boolean default false,
  p_can_delete_products boolean default false,
  p_can_manage_categories boolean default false,
  p_can_manage_settings boolean default false,
  p_can_view_orders boolean default false
)
returns void
language plpgsql
security definer
set search_path=public
as $$
declare v_user uuid;
begin
  if not public.is_admin() then raise exception 'المدير فقط يستطيع ربط حسابات الشركات'; end if;
  select user_id into v_user from public.company_account_requests where id=p_request_id;
  if v_user is null then raise exception 'طلب حساب الشركة غير موجود'; end if;
  if not exists(select 1 from public.companies where id=p_company_id) then raise exception 'الشركة غير موجودة'; end if;

  insert into public.company_users(user_id,company_id,can_manage_products,can_edit_products,can_delete_products,can_manage_categories,can_manage_settings,can_view_orders,active)
  values(v_user,p_company_id,p_can_manage_products,p_can_edit_products,p_can_delete_products,p_can_manage_categories,p_can_manage_settings,p_can_view_orders,true)
  on conflict(user_id) do update set
    company_id=excluded.company_id,
    can_manage_products=excluded.can_manage_products,
    can_edit_products=excluded.can_edit_products,
    can_delete_products=excluded.can_delete_products,
    can_manage_categories=excluded.can_manage_categories,
    can_manage_settings=excluded.can_manage_settings,
    can_view_orders=excluded.can_view_orders,
    active=true,
    updated_at=now();

  update public.profiles set role='company',company_id=p_company_id,store_id=null,can_edit_prices=false,verified=true where id=v_user;
  update public.company_account_requests set status='approved',company_id=p_company_id,reviewed_at=now(),reviewed_by=auth.uid() where id=p_request_id;
end $$;
revoke all on function public.admin_link_company_account(uuid,uuid,boolean,boolean,boolean,boolean,boolean,boolean) from public;
grant execute on function public.admin_link_company_account(uuid,uuid,boolean,boolean,boolean,boolean,boolean,boolean) to authenticated;

